'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../../catalogue/app.js'),'utf8');
const from=source.indexOf('const fwUnitOptions='),end=source.indexOf('function publicationResults',from);
assert(from>=0&&end>from,'Flowwow unit parser missing from catalogue script');
const helpers=new Function('escape','fwLabel','editing',source.slice(from,end)+';return {fwUnitOptions,fwDefaultUnit,fwMeasureControl};')(
 text=>String(text).replaceAll('&','&amp;').replaceAll('"','&quot;'),f=>f.field,null);
const field=(units,extra={})=>({field:'height',type:'measure',measure:units,...extra});
const render=(f,value)=>helpers.fwMeasureControl(f,value,'fw-height');
let f=field([{id:12,name:'centimeter'}]);
assert.equal(helpers.fwUnitOptions(f)[0].label,'см');
assert.match(render(f),/data-fw-measure="height" value="12"/);
assert.doesNotMatch(render(f),/<select|fw-unit-suffix|field-hint/);
f=field([{id:21},{id:22}]);
assert.match(render(f),/data-fw-measure="height" value="21"/);
assert.doesNotMatch(render(f),/<select|disabled|единица длины|field-hint/);
f=field([{id:21,name:'см'},{id:22,name:'м'}]);
assert.match(render(f),/data-fw-measure="height" value="21"/);
assert.doesNotMatch(render(f),/<select|fw-unit-suffix/);
f=field([{id:21},{id:22}],{defaultUnitId:22});
assert.match(render(f),/data-fw-measure="height" value="21"/);
assert.doesNotMatch(render(f),/<select/);
f=field([{id:21},{id:22}]);
assert.match(render(f,{val:15,measure:22}),/data-fw-measure="height" value="22"/);
assert.match(render(f,{val:15,measure:22}),/value="15"/);
f=field([{id:1,measure:'миллиметр'},{id:2,unit:{name:'метр'}}]);
assert.deepEqual(helpers.fwUnitOptions(f).map(o=>o.label),['мм','м']);
console.log('Flowwow unit UI checks passed: automatic first unit, no visible unit picker, preserved saved units.');
